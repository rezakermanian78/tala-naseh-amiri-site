// Regenerates supabase/seed.sql from the static content (src/content/*), which is also the
// site's offline fallback. Run: npm run db:seed:gen
import { writeFileSync } from 'node:fs'
import { fallbackData } from '../src/content/fallback'

type Value = string | number | boolean | null | readonly string[]

const lit = (v: Value): string => {
  // The only nullable column is skills.level (smallint); an untyped NULL in VALUES would be text.
  if (v === null) return 'null::smallint'
  if (typeof v === 'number' || typeof v === 'boolean') return String(v)
  if (typeof v === 'string') return `'${v.replace(/'/g, "''")}'`
  return v.length ? `array[${v.map(lit).join(', ')}]::text[]` : `'{}'::text[]`
}

const skip = new Set(['id', 'created_at', 'updated_at'])

/** Inserts rows only when the table is still empty, so re-running never overwrites edits. */
function insertIfEmpty(table: string, rows: readonly Record<string, Value>[]): string {
  if (!rows.length) return `-- ${table}: no rows\n`
  const cols = Object.keys(rows[0]).filter((c) => !skip.has(c))
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(', ')})`).join(',\n')
  return `insert into public.${table} (${cols.join(', ')})
select * from (values
${values}
) as v(${cols.join(', ')})
where not exists (select 1 from public.${table});
`
}

const { settings, skills, languages, education, projects, publications, contentWork, gallery } =
  fallbackData
const settingsCols = Object.keys(settings).filter((c) => c !== 'updated_at')
const settingsRow = settings as unknown as Record<string, Value>

const sql = `-- Generated by scripts/gen-seed.ts from src/content/* — do not edit by hand.
-- Imports the content the site shows today. Safe to re-run: it only fills empty tables
-- and never overwrites anything edited in the admin panel.
begin;

insert into public.site_settings (${settingsCols.join(', ')})
values (${settingsCols.map((c) => lit(settingsRow[c])).join(', ')})
on conflict (id) do nothing;

${[
  insertIfEmpty('skills', skills),
  insertIfEmpty('languages', languages),
  insertIfEmpty('education', education),
  insertIfEmpty('projects', projects),
  insertIfEmpty('publications', publications),
  insertIfEmpty('content_work', contentWork),
  insertIfEmpty('gallery', gallery),
].join('\n')}
commit;
`

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log('Wrote supabase/seed.sql')
